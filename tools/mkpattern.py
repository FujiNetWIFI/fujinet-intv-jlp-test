#!/usr/bin/env python3
"""Generate the N: test payload and the constants the ROM checks it against.

    mkpattern.py data/pattern.bin src/pattern.bas

The payload is PAT_LEN bytes where byte i is

    ((i & 255) ^ 0x5A ^ ((i >> 8) * 16)) & 255

which the ROM recomputes per byte without the JLP accelerators.  The ROM
packs bytes little-endian into 16-bit words (byte 2k low, byte 2k+1 high),
so the payload is exactly PAY_ROWS JLP flash rows of 96 words.

CRCs use the JLP CRC-16 unit's algorithm (polynomial $AD52, right shift,
one 16-bit word per step), as implemented by jzIntv's jlp.c and the cart's
cartridge.c, starting from CRC_INIT.
"""
import sys

PAT_LEN = 3072          # 16 rows * 96 words * 2 bytes
CRC_INIT = 0xFFFF
POLY = 0xAD52

# CRC known-answer vectors: (init, data word).
KAT = [
    (0xFFFF, 0x0000),
    (0xFFFF, 0xFFFF),
    (0x0000, 0x0001),
    (0x0000, 0x8000),
    (0x1234, 0x5678),
    (0xA55A, 0x5AA5),
    (0xFFFF, 0xC0DE),
    (0xBEEF, 0xDEC0),
]


def pattern_byte(i):
    return ((i & 255) ^ 0x5A ^ ((i >> 8) * 16)) & 255


def crc_word(crc, word):
    crc ^= word
    for _ in range(16):
        crc = (crc >> 1) ^ (POLY if crc & 1 else 0)
    return crc & 0xFFFF


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    data = bytes(pattern_byte(i) for i in range(PAT_LEN))
    words = [data[k] | (data[k + 1] << 8) for k in range(0, PAT_LEN, 2)]
    crc = CRC_INIT
    for word in words:
        crc = crc_word(crc, word)

    with open(sys.argv[1], "wb") as out:
        out.write(data)

    lines = [
        "' pattern.bas -- generated by tools/mkpattern.py; do not edit.",
        f"    CONST PAT_LEN = {PAT_LEN}",
        f"    CONST PAT_WORDS = {PAT_LEN // 2}",
        f"    CONST PAT_CRC = ${crc:04X}",
        f"    CONST CRC_INIT = ${CRC_INIT:04X}",
        f"    CONST KAT_COUNT = {len(KAT)}",
    ]
    with open(sys.argv[2], "w") as out:
        out.write("\n".join(lines) + "\n")
        # DATA tables must sit outside the straight-line path; main.bas
        # includes this file after its opening GOTO.
        out.write("kat_init:\n")
        out.write("    DATA " + ",".join(f"${i:04X}" for i, _ in KAT) + "\n")
        out.write("kat_data:\n")
        out.write("    DATA " + ",".join(f"${d:04X}" for _, d in KAT) + "\n")
        out.write("kat_out:\n")
        out.write("    DATA " + ",".join(f"${crc_word(i, d):04X}" for i, d in KAT) + "\n")


if __name__ == "__main__":
    main()
