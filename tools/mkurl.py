#!/usr/bin/env python3
"""Write the N: devicespec for the download tests as IntyBASIC DATA.

    mkurl.py <url> build/url.bas

The bytes are emitted as numbers, not a DATA string: IntyBASIC converts
DATA strings to GROM card numbers, and the devicespec must reach FujiNet as
plain ASCII, mixed case intact.
"""
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    spec = "N:" + sys.argv[1]
    raw = spec.encode("ascii")
    if len(raw) > 255:
        sys.exit("mkurl.py: devicespec longer than 255 bytes")
    with open(sys.argv[2], "w") as out:
        out.write("' url.bas -- generated by tools/mkurl.py from the Makefile's URL.\n")
        out.write(f"    CONST URL_LEN = {len(raw)}\n")
        out.write("url_text:\n")
        for start in range(0, len(raw), 16):
            out.write("    DATA " + ",".join(str(b) for b in raw[start:start + 16]) + "\n")


if __name__ == "__main__":
    main()
